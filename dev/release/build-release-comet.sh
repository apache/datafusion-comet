set -e

function usage {
  local NAME=$(basename $0)
  cat <<EOF
Usage: $NAME [options]

This script builds comet native binaries inside a docker image. The image is named
"comet-rm" and will be generated by this script. It then builds the jars and installs
them to a temporary local Maven repository.

Every jar is built twice: once with the system allocator, which is the artifact, and once with
the jemalloc allocator, which is installed next to it with the "jemalloc" classifier.

The branch is resolved to a single commit when the script starts, and the docker
images, the native binaries and the jars are all built from fresh clones of the repo
at that commit. Apart from this script, nothing is taken from the local checkout that
it is run from, so the checkout's current branch and local changes to other files do
not end up in the release.

Options are:

  -r [repo]   : git repo (default: ${REPO})
  -b [ref]    : git branch or tag to build (required)
  -t [tag]    : tag for the spark-rm docker image to use for building (default: "latest").
EOF
exit 1
}

function cleanup()
{
  if [ $CLEANUP != 0 ]
  then
    echo Cleaning up ...
    if [ "$(docker ps -a | grep comet-arm64-builder-container)" != "" ]
    then
      docker rm comet-arm64-builder-container
    fi
    if [ "$(docker ps -a | grep comet-amd64-builder-container)" != "" ]
    then
      docker rm comet-amd64-builder-container
    fi
    if [ -n "$BUILD_DIR" ]
    then
      rm -rf "$BUILD_DIR"
    fi
    CLEANUP=0
  fi
}

trap cleanup SIGINT SIGTERM EXIT

CLEANUP=0

REPO="https://github.com/apache/datafusion-comet.git"
BRANCH=
IMGTAG=latest

while getopts "b:hr:t:" opt; do
  case $opt in
    r) REPO="$OPTARG";;
    b) BRANCH="$OPTARG";;
    t) IMGTAG="$OPTARG" ;;
    h) usage ;;
    \?) error "Invalid option. Run with -h for help." ;;
  esac
done

if [ -z "$BRANCH" ]
then
  echo "Error: -b must specify the branch or tag to build"
  usage
fi

if git ls-remote --exit-code "$REPO" "refs/heads/$BRANCH" "refs/tags/$BRANCH" >/dev/null
then
  echo "Found branch or tag $BRANCH in $REPO"
else
  STATUS=$?
  if [ "$STATUS" -eq 2 ]
  then
    echo "Error: branch or tag '$BRANCH' does not exist in $REPO"
  else
    echo "Error: unable to check branch or tag '$BRANCH' in $REPO"
  fi
  exit 1
fi

echo "Building binaries from $REPO/$BRANCH"

# Check Java version
JAVA_VERSION=$(java -version 2>&1 | awk -F '"' '/version/ {print $2}' | awk -F '.' '{print $1}')
if [ "$JAVA_VERSION" -lt 17 ]; then
  echo "Error: Java version must be at least 17. Current version: $(java -version 2>&1 | head -n 1)"
  exit 1
fi
echo "Java version check passed: $JAVA_VERSION"

# Resolve the branch to a single commit, and build the docker images, the native binaries (in
# the docker containers) and the jars from fresh clones at that commit, so that they all match
# even if the branch moves during the build. Apart from this script, nothing is taken from the
# local checkout that it is run from, so its current branch, other local changes and stale
# build output (see https://github.com/apache/datafusion-comet/issues/2232) cannot leak into
# the release.
BUILD_DIR=$(mktemp -d /tmp/comet-release-build-XXXXX)
git clone "$REPO" "$BUILD_DIR"
git -C "$BUILD_DIR" checkout "$BRANCH"
COMMIT=$(git -C "$BUILD_DIR" rev-parse HEAD)
echo "Resolved $BRANCH to commit $COMMIT"

BUILDER_IMAGE_ARM64="comet-rm-arm64:$IMGTAG"
BUILDER_IMAGE_AMD64="comet-rm-amd64:$IMGTAG"

# Build the docker image in which we will do the build
docker build --no-cache \
  --platform=linux/arm64 \
  -t "$BUILDER_IMAGE_ARM64" \
  "$BUILD_DIR/dev/release/comet-rm"

docker build --no-cache \
  --platform=linux/amd64 \
  -t "$BUILDER_IMAGE_AMD64" \
  "$BUILD_DIR/dev/release/comet-rm"

# Run the builder container for each architecture. The entrypoint script will build the binaries

# AMD64
CLEANUP=1
echo "Building amd64 binary"
docker run \
   --name comet-amd64-builder-container \
   --memory 24g \
   --cpus 6 \
   --env "CARGO_BUILD_JOBS=${CARGO_BUILD_JOBS:-2}" \
   -it \
   --platform linux/amd64 \
   $BUILDER_IMAGE_AMD64 "${REPO}" "${COMMIT}" amd64

# ARM64
echo "Building arm64 binary"
docker run \
   --name comet-arm64-builder-container \
   --memory 24g \
   --cpus 6 \
   --env "CARGO_BUILD_JOBS=${CARGO_BUILD_JOBS:-2}" \
   -it \
   --platform linux/arm64 \
   $BUILDER_IMAGE_ARM64 "${REPO}" "${COMMIT}" arm64

echo "Building binaries completed"
echo "Copying native libraries out of the builder containers"

# Each container holds two builds of libcomet.so per architecture: "default" uses the system
# allocator and "jemalloc" uses the jemalloc allocator. See comet-rm/build-comet-native-libs.sh.
NATIVE_LIBS_DIR=$(mktemp -d /tmp/comet-native-libs-XXXXX)
for VARIANT in default jemalloc
do
  mkdir -p "$NATIVE_LIBS_DIR/$VARIANT/linux/amd64" "$NATIVE_LIBS_DIR/$VARIANT/linux/aarch64"
  docker cp \
    comet-amd64-builder-container:"/opt/comet-rm/lib/$VARIANT/libcomet.so" \
    "$NATIVE_LIBS_DIR/$VARIANT/linux/amd64/"
  docker cp \
    comet-arm64-builder-container:"/opt/comet-rm/lib/$VARIANT/libcomet.so" \
    "$NATIVE_LIBS_DIR/$VARIANT/linux/aarch64/"
done

# Build final jars
echo "Building uber jars and publishing them locally"
pushd "$BUILD_DIR"

LOCAL_REPO=$(mktemp -d /tmp/comet-staging-repo-XXXXX)
VERSION=$(./mvnw -q -DforceStdout help:evaluate -Dexpression=project.version | tail -n 1)
echo "Building version $VERSION"

# Every jar is built once per allocator. The jar with the system allocator is the artifact and
# the one with the jemalloc allocator is installed next to it with the "jemalloc" classifier, for
# example comet-spark-spark4.1_2.13-1.2.0-jemalloc.jar. Only the artifact has a pom and sources.
#
# Each entry is "<artifact id>|<Maven profiles>". The spark-4.x profiles pin their own Scala 2.13.x
# patch versions to match the corresponding Spark release, so the scala-2.13 profile is not used
# for them.
JAR_BUILDS=(
  "comet-spark-spark3.5_2.12|-P spark-3.5 -P scala-2.12"
  "comet-spark-spark3.5_2.13|-P spark-3.5 -P scala-2.13"
  "comet-spark-spark4.0_2.13|-P spark-4.0"
  "comet-spark-spark4.1_2.13|-P spark-4.1"
  "comet-spark-spark4.2_2.13|-P spark-4.2"
)

# Fail unless the jar holds exactly the native libraries built for the variant. The Maven build
# is incremental, so this catches a jar that kept the libraries of an earlier build.
function check_native_libs()
{
  local JAR=$1
  local VARIANT=$2
  local CHECK_DIR
  CHECK_DIR=$(mktemp -d /tmp/comet-jar-check-XXXXX)
  for PLATFORM_ARCH in linux/amd64 linux/aarch64
  do
    unzip -p "$JAR" "org/apache/comet/$PLATFORM_ARCH/libcomet.so" > "$CHECK_DIR/libcomet.so"
    if ! cmp -s "$CHECK_DIR/libcomet.so" "$NATIVE_LIBS_DIR/$VARIANT/$PLATFORM_ARCH/libcomet.so"
    then
      echo "Error: $JAR does not contain the $VARIANT build of $PLATFORM_ARCH/libcomet.so"
      rm -rf "$CHECK_DIR"
      exit 1
    fi
  done
  rm -rf "$CHECK_DIR"
}

# Install the jars with the system allocator, which are the artifacts
JVM_TARGET_DIR=$BUILD_DIR/spark/target/classes/org/apache/comet
mkdir -p "$JVM_TARGET_DIR"
cp -R "$NATIVE_LIBS_DIR/default/linux" "$JVM_TARGET_DIR/"

for BUILD in "${JAR_BUILDS[@]}"
do
  ARTIFACT_ID=${BUILD%%|*}
  PROFILES=${BUILD#*|}
  ./mvnw "-Dmaven.repo.local=${LOCAL_REPO}" $PROFILES -DskipTests install
  check_native_libs "spark/target/$ARTIFACT_ID-$VERSION.jar" default
done

# Rebuild with the jemalloc libraries. Clean first, so that nothing from the builds above is
# packaged again, then place the libraries where the build expects to find them. These builds only
# package the jars: installing them would replace the jars with the system allocator.
./mvnw "-Dmaven.repo.local=${LOCAL_REPO}" clean
mkdir -p "$JVM_TARGET_DIR"
cp -R "$NATIVE_LIBS_DIR/jemalloc/linux" "$JVM_TARGET_DIR/"

for BUILD in "${JAR_BUILDS[@]}"
do
  ARTIFACT_ID=${BUILD%%|*}
  PROFILES=${BUILD#*|}
  ./mvnw "-Dmaven.repo.local=${LOCAL_REPO}" $PROFILES -P jemalloc -DskipTests package
  JEMALLOC_JAR="spark/target/$ARTIFACT_ID-$VERSION.jar"
  check_native_libs "$JEMALLOC_JAR" jemalloc
  cp "$JEMALLOC_JAR" \
    "$LOCAL_REPO/org/apache/datafusion/$ARTIFACT_ID/$VERSION/$ARTIFACT_ID-$VERSION-jemalloc.jar"
done

echo "Installed to local repo: ${LOCAL_REPO}"
echo "Built from commit: ${COMMIT}"

rm -rf "$NATIVE_LIBS_DIR"
popd
